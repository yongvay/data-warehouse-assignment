-- ============================================================================
--  BMIT3003 DATA WAREHOUSE TECHNOLOGY - ASSIGNMENT
--  TASK 1(b) : PHYSICAL DESIGN
--  System    : 88 Speedmart Grocery - Sales, Returns, Delivery & Loyalty
--              Data Warehouse
--  DBMS      : Oracle
-- ----------------------------------------------------------------------------
--  STRUCTURE : 8 dimension tables + 4 fact tables (fact constellation)
--              CUSTOMER_DIM is a Slowly Changing Dimension Type 2.
--
--  CONVENTION: The warehouse is a SELF-CONTAINED schema owned by the DW user.
--              The operational tables built by Task2_DDL.sql are owned by a
--              SEPARATE Oracle user, so the warehouse declares NO foreign key
--              into that schema.  Every foreign key below points at another
--              warehouse table (fact -> dimension).
--
--              Each dimension still stores its operational identifier for
--              lineage and for ETL matching, as a NOT NULL UNIQUE column.
--              Referential integrity back to the operational system is
--              enforced by the ETL and documented in the source-to-target
--              mapping, not by a database constraint.  This is deliberate:
--              a Type 2 dimension must retain history that the operational
--              system has already deleted, which a foreign key would forbid.
--
--  NAMING    : snake_case throughout.
--
--  RESERVED IDENTIFIERS FOR SEEDED ROWS
--              Every dimension is seeded with one row keyed -1 representing
--              'Unknown', which uses the reserved operational identifier
--              'UNKN'.  PROMOTION_DIM additionally seeds a row keyed 0
--              representing 'No Promotion', which uses 'NONE'.
--
--  PREREQUISITE FOR TASK 2
--              The ETL reads the operational tables across schemas, so the
--              operational owner must first run:
--                  GRANT SELECT ON <table> TO dw;
--              for each of the 18 source tables.
-- ============================================================================

