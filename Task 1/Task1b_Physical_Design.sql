    CONSTRAINT chk_branch_dim_dqflag CHECK (dq_flag IN ('V','S','D'))
);

-- ----------------------------------------------------------------------------
--  5. ADDRESS_DIM  (Type 1)  -  ship-to geography for DELIVERY_FACT
