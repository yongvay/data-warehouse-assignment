    branch_key         NUMBER(10)    NOT NULL,
    branch_id          VARCHAR2(5)   NOT NULL,                   
    branch_name        VARCHAR2(60)  DEFAULT 'Unknown' NOT NULL,
    branch_city        VARCHAR2(50)  DEFAULT 'Unknown' NOT NULL,
