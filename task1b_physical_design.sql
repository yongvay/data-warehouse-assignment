/* ============================================================================
   7. ROLE-PLAYING VIEWS
   DATE_DIM is referenced three times across the two facts. Exposing it to the
   BI layer through two aliased views removes the self-join ambiguity for end
   users without duplicating the underlying data.
   ============================================================================ */
CREATE OR REPLACE VIEW ORDER_DATE_DIM AS
SELECT date_key          AS order_date_key,
       cal_date          AS order_date,
       full_desc         AS order_full_desc,
       day_week          AS order_day_week,
       cal_week_year     AS order_week_year,
       cal_month_name    AS order_month_name,
       cal_year_month    AS order_year_month,
       cal_quarter       AS order_quarter,
       cal_year_quarter  AS order_year_quarter,
       cal_year          AS order_year,
       holiday_ind       AS order_holiday_ind,
       weekday_ind       AS order_weekday_ind,
       festive_event     AS order_festive_event
FROM   DATE_DIM;

CREATE OR REPLACE VIEW RETURN_DATE_DIM AS
SELECT date_key          AS return_date_key,
       cal_date          AS return_date,
       full_desc         AS return_full_desc,
       day_week          AS return_day_week,
       cal_week_year     AS return_week_year,
       cal_month_name    AS return_month_name,
       cal_year_month    AS return_year_month,
       cal_quarter       AS return_quarter,
       cal_year_quarter  AS return_year_quarter,
       cal_year          AS return_year,
       holiday_ind       AS return_holiday_ind,
       weekday_ind       AS return_weekday_ind,
       festive_event     AS return_festive_event
FROM   DATE_DIM;

